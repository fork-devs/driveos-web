export function tasksFor(technicianName: string): TaskView[] {
  return workOrders
    .flatMap((o) =>
      o.tasks
        .filter((t) => t.assignee === technicianName)
        .map((t) => ({
          id: t.id,
          title: t.title,
          status: t.status,
          orderCode: o.code,
          plate: o.plate,
          vehicle: o.vehicle,
          parts: t.parts,
        })),
    );
}
